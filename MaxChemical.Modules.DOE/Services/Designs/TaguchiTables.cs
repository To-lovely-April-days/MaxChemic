    /// <summary>
    /// Taguchi 标准正交表 (L 表)。
    ///
    /// 数据来源: Taguchi & Konishi, "Taguchi Methods: Orthogonal Arrays and
    /// Linear Graphs" (1987), Minitab 内置表。
    ///
    /// 表格式:
    ///   - 行 = 实验次数
    ///   - 列 = 因子位
    ///   - 值 = 水平索引 (从 1 开始, 对应因子水平标签)
    ///
    /// 支持的 L 表:
    ///   L4  (2^3)    : 3 个 2水平因子 / 4 runs
    ///   L8  (2^7)    : 7 个 2水平因子 / 8 runs
    ///   L9  (3^4)    : 4 个 3水平因子 / 9 runs
    ///   L12 (2^11)   : 11 个 2水平因子 / 12 runs
    ///   L16 (2^15)   : 15 个 2水平因子 / 16 runs
    ///   L16b(4^5)    : 5 个 4水平因子 / 16 runs
    ///   L18 (2^1 × 3^7): 混合表, 1 个 2水平 + 7 个 3水平 / 18 runs
    ///   L25 (5^6)    : 6 个 5水平因子 / 25 runs
    ///   L27 (3^13)   : 13 个 3水平因子 / 27 runs
    ///   L32 (2^31)   : 31 个 2水平因子 / 32 runs
    ///   L36 (2^11 × 3^12): 混合表 / 36 runs
    /// </summary>
    internal static class TaguchiTables
    {
        public record LArray(string Name, int Runs, int MaxFactors, int Levels, int[,] Matrix);

        // ── L4 (2^3, 4 runs) ──
