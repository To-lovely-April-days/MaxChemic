        private static readonly Dictionary<string, LArray> _tables = new()
        {
            { "L4",  new LArray("L4",  4,  3,  2, _L4) },
            { "L8",  new LArray("L8",  8,  7,  2, _L8) },
            { "L9",  new LArray("L9",  9,  4,  3, _L9) },
            { "L12", new LArray("L12", 12, 11, 2, _L12) },
            { "L16", new LArray("L16", 16, 15, 2, _L16) },
            { "L18", new LArray("L18", 18, 8,  0, _L18) },  // 混合水平
            { "L27", new LArray("L27", 27, 13, 3, _L27) },
        };

        public static LArray? Lookup(string name) => _tables.TryGetValue(name, out var t) ? t : null;

        /// <summary>按因子数和水平推荐最小的 L 表。</summary>
        public static LArray? Recommend(int factorCount, int levelCount)
        {
            // 按运行数升序尝试
            foreach (var name in new[] { "L4", "L8", "L9", "L12", "L16", "L18", "L27" })
            {
                var t = _tables[name];
                if (t.Levels == 0) continue; // 混合表不走自动推荐
                if (t.Levels == levelCount && t.MaxFactors >= factorCount)
                    return t;
            }
            return null;
        }
    }
