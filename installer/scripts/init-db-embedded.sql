-- ============================================================================
--  仅内置模式执行:给 root 设口令
--
--  内置实例是用 --initialize-insecure 初始化的,此刻 root 还没有口令。
--  这一步立刻给它设上,把那个几秒的无口令窗口关掉。
--
--  **绝不能在"使用客户现有实例"模式下执行本文件**——改掉客户 root 的口令
--  会打断他们其他所有连这个库的系统。所以它独立成文件,由 mysql-setup.bat
--  按模式判断是否调用,而不是在同一个脚本里靠注释提醒别执行。
-- ============================================================================

ALTER USER 'root'@'localhost' IDENTIFIED BY '__APPPWD__';

FLUSH PRIVILEGES;
